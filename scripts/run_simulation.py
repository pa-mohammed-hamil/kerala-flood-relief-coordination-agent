def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run offline synthetic Kerala Flood AI simulations."
        )
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/demo"),
        help="Input JSON dataset directory",
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/simulation"),
        help="Simulation output directory",
    )

    parser.add_argument(
        "--scenario",
        choices=sorted(SCENARIOS),
        default="heavy_rainfall",
    )

    parser.add_argument(
        "--steps",
        type=int,
        default=24,
        help="Number of simulated hourly steps",
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    args = parser.parse_args()

    if not 1 <= args.steps <= 1000:
        parser.error(
            "--steps must be between 1 and 1000."
        )

    return args


