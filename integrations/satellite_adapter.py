@dataclass(frozen=True)
class SatelliteBoundingBox:
    west: float
    south: float
    east: float
    north: float

    def __post_init__(self) -> None:
        values = (
            self.west,
            self.south,
            self.east,
            self.north,
        )

        if not all(
            isinstance(value, (int, float))
            and not isinstance(value, bool)
            and math.isfinite(value)
            for value in values
        ):
            raise SatelliteValidationError(
                "Invalid bounding-box values"
            )

        if not (
            -180 <= self.west < self.east <= 180
        ):
            raise SatelliteValidationError(
                "Invalid longitude bounds"
            )

        if not (
            -90 <= self.south < self.north <= 90
        ):
            raise SatelliteValidationError(
                "Invalid latitude bounds"
            )

    def to_list(self) -> list[float]:
        return [
            self.west,
            self.south,
            self.east,
            self.north,
        ]

    @classmethod
    def for_district(
        cls,
        district: str,
    ) -> "SatelliteBoundingBox":
        selected = normalize_district(
            district
        )

        return cls(
            *KERALA_DISTRICT_BBOXES[selected]
        )


