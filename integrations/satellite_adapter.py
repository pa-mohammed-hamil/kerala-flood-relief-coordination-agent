class SatelliteGeoJSONExporter:
    @staticmethod
    def scene_feature(
        scene: SatelliteScene,
    ) -> dict[str, Any]:
        bbox = scene.bounding_box

        coordinates = [
            [bbox.west, bbox.south],
            [bbox.east, bbox.south],
            [bbox.east, bbox.north],
            [bbox.west, bbox.north],
            [bbox.west, bbox.south],
        ]

        return {
            "type": "Feature",
            "geometry": {
                "type": "Polygon",
                "coordinates": [
                    coordinates
                ],
            },
            "properties": {
                "scene_id": scene.scene_id,
                "collection": scene.collection_id,
                "platform": scene.platform.value,
                "sensor_type": (
                    scene.sensor_type.value
                ),
                "acquired_at": (
                    scene.acquired_at.isoformat()
                ),
                "cloud_cover_percent": (
                    scene.cloud_cover_percent
                ),
                "data_status": (
                    scene.data_status.value
                ),
                "verification": (
                    scene.verification.value
                ),
            },
        }

    @staticmethod
    def to_geojson(
        scenes: Sequence[SatelliteScene],
    ) -> str:
        return json.dumps(
            {
                "type": "FeatureCollection",
                "features": [
                    SatelliteGeoJSONExporter.scene_feature(
                        scene
                    )
                    for scene in scenes
                ],
            },
            ensure_ascii=False,
            indent=2,
        )


