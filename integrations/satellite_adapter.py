class SatelliteHTTPClient:
    RETRYABLE_STATUS_CODES = {
        429,
        500,
        502,
        503,
        504,
    }

    def __init__(
        self,
        config: SatelliteAdapterConfig,
    ) -> None:
        if httpx is None:
            raise SatelliteConfigurationError(
                "Install httpx: pip install httpx"
            )

        self.config = config

        self._client: httpx.AsyncClient | None = None

    def _headers(self) -> dict[str, str]:
        headers = {
            "Accept": "application/json",
            "User-Agent": (
                "KeralaFloodReliefAgent/1.0"
            ),
        }

        if (
            self.config.auth_type
            == SatelliteAuthType.API_KEY
        ):
            headers[
                self.config.api_key_header
            ] = self.config.api_key or ""

        elif (
            self.config.auth_type
            == SatelliteAuthType.BEARER
        ):
            headers["Authorization"] = (
                f"Bearer {self.config.bearer_token}"
            )

        return headers

    async def _get_client(
        self,
    ) -> httpx.AsyncClient:
        if self._client is None:
            self._client = httpx.AsyncClient(
                timeout=self.config.timeout_seconds,
                headers=self._headers(),
                follow_redirects=False,
                trust_env=False,
            )

        return self._client

    def _validate_asset_url(
        self,
        url: str,
    ) -> None:
        parsed = urlparse(url)

        if (
            parsed.scheme != "https"
            or not parsed.hostname
            or parsed.username
            or parsed.password
        ):
            raise SatelliteAuthorizationError(
                "Invalid satellite asset URL"
            )

        if (
            not self.config.allowed_asset_hosts
            or parsed.hostname
            not in self.config.allowed_asset_hosts
        ):
            raise SatelliteAuthorizationError(
                "Satellite asset host is not allowlisted"
            )

    async def search(
        self,
        request: SatelliteSearchRequest,
    ) -> Mapping[str, Any]:
        client = await self._get_client()

        url = (
            self.config.stac_base_url.rstrip("/")
            + self.config.search_endpoint
        )

        body = {
            "bbox": request.bounding_box.to_list(),
            "datetime": (
                f"{request.start_time.isoformat()}/"
                f"{request.end_time.isoformat()}"
            ),
            "collections": list(
                request.collections
            ),
            "limit": min(
                request.max_items,
                self.config.max_search_items,
            ),
        }

        last_error: Exception | None = None

        for attempt in range(
            self.config.max_retries + 1
        ):
            try:
                async with client.stream(
                    "POST",
                    url,
                    json=body,
                ) as response:
                    if response.status_code in (401, 403):
                        raise SatelliteAuthenticationError(
                            "Catalog authentication failed"
                        )

                    if (
                        response.status_code
                        in self.RETRYABLE_STATUS_CODES
                    ):
                        raise SatelliteRequestError(
                            "Temporary catalog failure"
                        )

                    response.raise_for_status()

                    chunks = []
                    total = 0

                    async for chunk in response.aiter_bytes():
                        total += len(chunk)

                        if total > (
                            self.config.max_response_bytes
                        ):
                            raise SatelliteResponseError(
                                "Catalog response too large"
                            )

                        chunks.append(chunk)

                payload = json.loads(
                    b"".join(chunks)
                )

                if not isinstance(payload, Mapping):
                    raise SatelliteResponseError(
                        "Invalid STAC response"
                    )

                return payload

            except (
                SatelliteAuthenticationError,
                SatelliteResponseError,
            ):
                raise

            except (
                SatelliteRequestError,
                httpx.TimeoutException,
                httpx.TransportError,
            ) as exc:
                last_error = exc

                if attempt >= self.config.max_retries:
                    break

                delay = (
                    self.config.retry_base_seconds
                    * (2 ** attempt)
                )

                delay += random.uniform(
                    0,
                    min(1.0, delay * 0.2),
                )

                await asyncio.sleep(delay)

            except httpx.HTTPStatusError as exc:
                raise SatelliteRequestError(
                    f"Catalog HTTP "
                    f"{exc.response.status_code}"
                ) from exc

            except json.JSONDecodeError as exc:
                raise SatelliteResponseError(
                    "Invalid catalog JSON"
                ) from exc

        raise SatelliteRequestError(
            "Catalog request failed"
        ) from last_error

    async def download_asset(
        self,
        *,
        scene_id: str,
        asset: SatelliteAsset,
        destination: Path,
    ) -> SatelliteDownloadResult:
        self._validate_asset_url(
            asset.href
        )

        client = await self._get_client()

        destination = destination.resolve()

        destination.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        temporary_path: Path | None = None

        try:
            with tempfile.NamedTemporaryFile(
                mode="wb",
                prefix=".satellite_",
                suffix=".download",
                dir=destination.parent,
                delete=False,
            ) as temporary:
                temporary_path = Path(
                    temporary.name
                )

                digest = hashlib.sha256()
                total = 0

                async with client.stream(
                    "GET",
                    asset.href,
                    headers={
                        "Accept": "*/*",
                        # Do not forward catalog credentials
                        # to unrelated asset hosts.
                        "Authorization": "",
                    },
                ) as response:
                    response.raise_for_status()

                    async for chunk in response.aiter_bytes():
                        total += len(chunk)

                        if total > (
                            self.config.max_download_bytes
                        ):
                            raise SatelliteDownloadError(
                                "Asset download exceeds limit"
                            )

                        digest.update(chunk)
                        temporary.write(chunk)

            if total == 0:
                raise SatelliteDownloadError(
                    "Empty satellite asset"
                )

            os.replace(
                temporary_path,
                destination,
            )

            temporary_path = None

            return SatelliteDownloadResult(
                scene_id=scene_id,
                asset_key=asset.asset_key,
                local_path=destination,
                size_bytes=total,
                sha256=digest.hexdigest(),
                downloaded_at=utc_now(),
                source_uri=asset.href,
                requires_validation=True,
            )

        except httpx.HTTPError as exc:
            raise SatelliteDownloadError(
                "Satellite asset download failed"
            ) from exc

        finally:
            if (
                temporary_path is not None
                and temporary_path.exists()
            ):
                temporary_path.unlink()


    async def close(self) -> None:
        if self._client is not None:
            await self._client.aclose()
            self._client = None


