class SatelliteAuditLogger:
    def __init__(
        self,
        max_events: int = 1000,
    ) -> None:
        self.max_events = max_events
        self._events: list[
            SatelliteAuditEvent
        ] = []

    def record(
        self,
        *,
        action: str,
        tenant_id: str,
        status: str,
        scene_id: str | None = None,
        metadata: Mapping[str, Any] | None = None,
    ) -> None:
        self._events.append(
            SatelliteAuditEvent(
                event_id=generate_id(),
                action=action,
                timestamp=utc_now(),
                tenant_id=tenant_id,
                scene_id=scene_id,
                status=status,
                metadata=metadata or {},
            )
        )

        if len(self._events) > self.max_events:
            self._events = self._events[
                -self.max_events:
            ]

    def events(
        self,
        *,
        tenant_id: str,
    ) -> list[SatelliteAuditEvent]:
        return [
            event
            for event in self._events
            if event.tenant_id == tenant_id
        ]


# ============================================================
# MAIN SATELLITE ADAPTER
# ============================================================

class SatelliteAdapter:
    def __init__(
        self,
        config: SatelliteAdapterConfig,
    ) -> None:
        self.config = config

        self.http_client = SatelliteHTTPClient(
            config
        )

        self.parser = STACSceneParser(
            config
        )

        self.source_policy = SatelliteSourcePolicy(
            config
        )

        self.scene_filter = SatelliteSceneFilter()

        self.flood_analysis = (
            SatelliteFloodAnalysisAdapter()
        )

        self.audit = SatelliteAuditLogger()

    async def search_scenes(
        self,
        request: SatelliteSearchRequest,
    ) -> SatelliteSearchResponse:
        self.source_policy.require_verified()

        payload = await self.http_client.search(
            request
        )

        scenes = self.parser.parse(
            payload
        )

        scenes = [
            scene
            for scene in scenes
            if scene.collection_id
            in request.collections
            and request.start_time
            <= scene.acquired_at
            <= request.end_time
        ]

        scenes = self.scene_filter.filter(
            scenes,
            max_cloud_cover_percent=(
                request.max_cloud_cover_percent
            ),
        )

        self.audit.record(
            action="search_scenes",
            tenant_id=request.tenant_id,
            status="completed",
            metadata={
                "scene_count": len(scenes),
            },
        )

        warnings = []

        if any(
            scene.data_status
            != SatelliteDataStatus.CURRENT
            for scene in scenes
        ):
            warnings.append(
                "Some imagery is older than "
                "the configured freshness window"
            )

        warnings.append(
            "Search bounding boxes are approximate "
            "and do not represent official district "
            "boundaries"
        )

        return SatelliteSearchResponse(
            request=request,
            scenes=tuple(scenes),
            retrieved_at=utc_now(),
            provider=self.config.stac_base_url,
            warnings=tuple(warnings),
        )

    async def search_district(
        self,
        *,
        district: str,
        start_time: datetime,
        end_time: datetime,
        collections: Sequence[str],
        max_items: int = 50,
        max_cloud_cover_percent: float | None = None,
        tenant_id: str = "default",
    ) -> SatelliteSearchResponse:
        request = SatelliteSearchRequest(
            bounding_box=(
                SatelliteBoundingBox.for_district(
                    district
                )
            ),
            start_time=parse_timestamp(
                start_time
            ),
            end_time=parse_timestamp(
                end_time
            ),
            collections=tuple(
                collections
            ),
            max_items=max_items,
            max_cloud_cover_percent=(
                max_cloud_cover_percent
            ),
            tenant_id=tenant_id,
        )

        return await self.search_scenes(
            request
        )

    async def download_scene_asset(
        self,
        *,
        scene: SatelliteScene,
        asset_key: str,
        destination: Path,
        tenant_id: str,
    ) -> SatelliteDownloadResult:
        self.source_policy.require_verified()

        if (
            scene.verification
            != SatelliteVerification.VERIFIED_PROVIDER
        ):
            raise SatelliteAuthorizationError(
                "Unverified satellite scene"
            )

        asset = scene.assets.get(
            asset_key
        )

        if asset is None:
            raise SatelliteValidationError(
                "Asset not found"
            )

        result = await self.http_client.download_asset(
            scene_id=scene.scene_id,
            asset=asset,
            destination=destination,
        )

        self.audit.record(
            action="download_asset",
            tenant_id=tenant_id,
            scene_id=scene.scene_id,
            status="completed",
            metadata={
                "asset_key": asset_key,
                "size_bytes": result.size_bytes,
                "sha256": result.sha256,
            },
        )

        return result

    def prepare_flood_analysis(
        self,
        *,
        scene: SatelliteScene,
        tenant_id: str,
        downloaded_assets: Mapping[
            str,
            SatelliteDownloadResult,
        ],
    ) -> SatelliteAnalysisInput:
        result = self.flood_analysis.prepare(
            scene,
            tenant_id=tenant_id,
            downloaded_assets=downloaded_assets,
        )

        self.audit.record(
            action="prepare_flood_analysis",
            tenant_id=tenant_id,
            scene_id=scene.scene_id,
            status="review_required",
        )

        return result

    async def close(self) -> None:
        await self.http_client.close()

    async def __aenter__(
        self,
    ) -> "SatelliteAdapter":
        return self

    async def __aexit__(
        self,
        exc_type: Any,
        exc: Any,
        traceback: Any,
    ) -> None:
        await self.close()


