class SatelliteSourcePolicy:
    def __init__(
        self,
        config: SatelliteAdapterConfig,
    ) -> None:
        self.config = config

    @property
    def verification(
        self,
    ) -> SatelliteVerification:
        return (
            SatelliteVerification.VERIFIED_PROVIDER
            if self.config.source_verified
            else SatelliteVerification.UNVERIFIED
        )

    def require_verified(self) -> None:
        if (
            self.config.require_verified_source
            and not self.config.source_verified
        ):
            raise SatelliteAuthorizationError(
                "Satellite provider has not been "
                "independently verified"
            )

    def scene_status(
        self,
        acquired_at: datetime,
        *,
        now: datetime,
    ) -> SatelliteDataStatus:
        age = now - acquired_at

        if age < timedelta(0):
            return (
                SatelliteDataStatus.FUTURE_TIMESTAMP
            )

        if age > timedelta(
            hours=self.config.max_scene_age_hours
        ):
            return SatelliteDataStatus.STALE

        return SatelliteDataStatus.CURRENT


