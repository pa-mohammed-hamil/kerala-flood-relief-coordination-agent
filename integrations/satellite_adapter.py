# ============================================================

class SatelliteFloodAnalysisAdapter:
    """
    Prepares satellite imagery for downstream
    computer vision and flood segmentation.

    This adapter does not run an AI model
    and does not infer flood extent.
    """

    REQUIRED_SAR_ASSETS = {
        SatelliteAssetType.VV,
        SatelliteAssetType.VH,
    }

    REQUIRED_OPTICAL_ASSETS = {
        SatelliteAssetType.GREEN,
        SatelliteAssetType.NIR,
    }

    def prepare(
        self,
        scene: SatelliteScene,
        *,
        tenant_id: str,
        downloaded_assets: Mapping[
            str,
            SatelliteDownloadResult,
        ],
    ) -> SatelliteAnalysisInput:
        if (
            scene.verification
            != SatelliteVerification.VERIFIED_PROVIDER
        ):
            raise SatelliteAuthorizationError(
                "Unverified satellite scene"
            )

        if (
            scene.data_status
            == SatelliteDataStatus.FUTURE_TIMESTAMP
        ):
            raise SatelliteValidationError(
                "Invalid acquisition timestamp"
            )

        available_types = {
            scene.assets[key].asset_type
            for key in downloaded_assets
            if key in scene.assets
        }

        if scene.sensor_type == SatelliteSensorType.SAR:
            if not (
                self.REQUIRED_SAR_ASSETS
                <= available_types
            ):
                raise SatelliteProcessingError(
                    "SAR VV and VH assets required"
                )

        elif (
            scene.sensor_type
            == SatelliteSensorType.OPTICAL
        ):
            if not (
                self.REQUIRED_OPTICAL_ASSETS
                <= available_types
            ):
                raise SatelliteProcessingError(
                    "Optical green and NIR bands required"
                )

        else:
            raise SatelliteProcessingError(
                "Unsupported sensor type"
            )

        for key, result in downloaded_assets.items():
            if result.scene_id != scene.scene_id:
                raise SatelliteValidationError(
                    "Asset belongs to another scene"
                )

            if key not in scene.assets:
                raise SatelliteValidationError(
                    "Unexpected asset key"
                )

            if result.asset_key != key:
                raise SatelliteValidationError(
                    "Asset identity mismatch"
                )

        return SatelliteAnalysisInput(
            analysis_id=generate_id(),
            scene_id=scene.scene_id,
            tenant_id=tenant_id,
            sensor_type=scene.sensor_type,
            asset_paths={
                key: str(result.local_path)
                for key, result
                in downloaded_assets.items()
            },
            acquired_at=scene.acquired_at,
            bounding_box=scene.bounding_box,
            status=SatelliteAnalysisStatus.PREPARED,
            requires_human_review=True,
            metadata={
                "platform": scene.platform.value,
                "collection": scene.collection_id,
                "cloud_cover_percent": (
                    scene.cloud_cover_percent
                ),
                "note": (
                    "Imagery must undergo calibration, "
                    "reprojection, quality checks and "
                    "human-reviewed flood validation"
                ),
            },
        )


