class STACSceneParser:
    def __init__(
        self,
        config: SatelliteAdapterConfig,
    ) -> None:
        self.config = config

        self.source_policy = (
            SatelliteSourcePolicy(config)
        )

    @staticmethod
    def _platform(
        properties: Mapping[str, Any],
        collection_id: str,
    ) -> SatellitePlatform:
        text = (
            str(
                properties.get("platform", "")
            )
            + " "
            + collection_id
        ).casefold()

        if "sentinel-1" in text:
            return SatellitePlatform.SENTINEL_1

        if "sentinel-2" in text:
            return SatellitePlatform.SENTINEL_2

        if "landsat-8" in text:
            return SatellitePlatform.LANDSAT_8

        if "landsat-9" in text:
            return SatellitePlatform.LANDSAT_9

        return SatellitePlatform.OTHER

    @staticmethod
    def _sensor(
        platform: SatellitePlatform,
    ) -> SatelliteSensorType:
        if platform == SatellitePlatform.SENTINEL_1:
            return SatelliteSensorType.SAR

        if platform in (
            SatellitePlatform.SENTINEL_2,
            SatellitePlatform.LANDSAT_8,
            SatellitePlatform.LANDSAT_9,
        ):
            return SatelliteSensorType.OPTICAL

        return SatelliteSensorType.UNKNOWN

    @staticmethod
    def _asset_type(
        key: str,
    ) -> SatelliteAssetType:
        normalized = key.casefold()

        aliases = {
            "vv": SatelliteAssetType.VV,
            "vh": SatelliteAssetType.VH,
            "hh": SatelliteAssetType.HH,
            "hv": SatelliteAssetType.HV,
            "red": SatelliteAssetType.RED,
            "green": SatelliteAssetType.GREEN,
            "blue": SatelliteAssetType.BLUE,
            "nir": SatelliteAssetType.NIR,
            "swir": SatelliteAssetType.SWIR,
            "scl": SatelliteAssetType.SCL,
            "visual": SatelliteAssetType.VISUAL,
            "b04": SatelliteAssetType.RED,
            "b03": SatelliteAssetType.GREEN,
            "b02": SatelliteAssetType.BLUE,
            "b08": SatelliteAssetType.NIR,
            "b11": SatelliteAssetType.SWIR,
        }

        return aliases.get(
            normalized,
            SatelliteAssetType.OTHER,
        )

    def parse(
        self,
        payload: Mapping[str, Any],
        *,
        now: datetime | None = None,
    ) -> list[SatelliteScene]:
        now = now or utc_now()

        features = payload.get(
            "features",
            [],
        )

        if not isinstance(features, list):
            raise SatelliteResponseError(
                "STAC features must be a list"
            )

        if len(features) > (
            self.config.max_search_items
        ):
            raise SatelliteResponseError(
                "Too many STAC features"
            )

        output = []

        for item in features:
            if not isinstance(item, Mapping):
                raise SatelliteResponseError(
                    "Invalid STAC feature"
                )

            scene_id = str(
                item.get("id", "")
            )

            collection_id = str(
                item.get("collection", "")
            )

            if not scene_id or not collection_id:
                raise SatelliteResponseError(
                    "Missing STAC scene identifiers"
                )

            properties = item.get(
                "properties",
                {},
            )

            if not isinstance(properties, Mapping):
                raise SatelliteResponseError(
                    "Invalid STAC properties"
                )

            acquired_at = parse_timestamp(
                properties.get("datetime")
                or properties.get("start_datetime")
            )

            raw_bbox = item.get(
                "bbox",
            )

            if (
                not isinstance(raw_bbox, list)
                or len(raw_bbox) not in (4, 6)
            ):
                raise SatelliteResponseError(
                    "Invalid STAC bounding box"
                )

            if len(raw_bbox) == 4:
                west, south, east, north = raw_bbox
            else:
                west = raw_bbox[0]
                south = raw_bbox[1]
                east = raw_bbox[3]
                north = raw_bbox[4]

            bbox = SatelliteBoundingBox(
                west=finite_number(west, "west"),
                south=finite_number(south, "south"),
                east=finite_number(east, "east"),
                north=finite_number(north, "north"),
            )

            platform = self._platform(
                properties,
                collection_id,
            )

            cloud_cover = optional_number(
                properties.get(
                    "eo:cloud_cover"
                ),
                "cloud cover",
            )

            if (
                cloud_cover is not None
                and not 0 <= cloud_cover <= 100
            ):
                raise SatelliteValidationError(
                    "Invalid cloud cover"
                )

            raw_assets = item.get(
                "assets",
                {},
            )

            if not isinstance(raw_assets, Mapping):
                raise SatelliteResponseError(
                    "Invalid STAC assets"
                )

            assets = {}

            for key, raw_asset in raw_assets.items():
                if not isinstance(
                    raw_asset,
                    Mapping,
                ):
                    continue

                href = raw_asset.get(
                    "href"
                )

                if not isinstance(href, str):
                    continue

                parsed_url = urlparse(
                    href
                )

                if (
                    parsed_url.scheme != "https"
                    or not parsed_url.hostname
                ):
                    continue

                assets[str(key)] = SatelliteAsset(
                    asset_key=str(key),
                    href=href,
                    asset_type=self._asset_type(
                        str(key)
                    ),
                    media_type=raw_asset.get(
                        "type"
                    ),
                    roles=tuple(
                        str(role)
                        for role in raw_asset.get(
                            "roles",
                            [],
                        )
                    ),
                    title=raw_asset.get(
                        "title"
                    ),
                )

            output.append(
                SatelliteScene(
                    scene_id=scene_id,
                    collection_id=collection_id,
                    platform=platform,
                    sensor_type=self._sensor(
                        platform
                    ),
                    acquired_at=acquired_at,
                    bounding_box=bbox,
                    cloud_cover_percent=cloud_cover,
                    assets=assets,
                    source_uri=(
                        self.config.stac_base_url
                    ),
                    verification=(
                        self.source_policy.verification
                    ),
                    data_status=(
                        self.source_policy.scene_status(
                            acquired_at,
                            now=now,
                        )
                    ),
                    retrieved_at=now,
                )
            )

        return output


# ============================================================
# SCENE FILTERING
# ============================================================

class SatelliteSceneFilter:
    @staticmethod
    def filter(
        scenes: Sequence[SatelliteScene],
        *,
        max_cloud_cover_percent: float | None = None,
        current_only: bool = False,
        sensor_type: SatelliteSensorType | None = None,
    ) -> list[SatelliteScene]:
        output = []

        for scene in scenes:
            if (
                current_only
                and scene.data_status
                != SatelliteDataStatus.CURRENT
            ):
                continue

            if (
                sensor_type is not None
                and scene.sensor_type != sensor_type
            ):
                continue

            if (
                max_cloud_cover_percent is not None
                and scene.sensor_type
                == SatelliteSensorType.OPTICAL
            ):
                if (
                    scene.cloud_cover_percent is None
                    or scene.cloud_cover_percent
                    > max_cloud_cover_percent
                ):
                    continue

            output.append(scene)

        return sorted(
            output,
            key=lambda item: item.acquired_at,
            reverse=True,
        )


