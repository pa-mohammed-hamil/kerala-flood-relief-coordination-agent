@dataclass(frozen=True)
class SatelliteAdapterConfig:
    stac_base_url: str

    search_endpoint: str = "/search"

    auth_type: SatelliteAuthType = (
        SatelliteAuthType.NONE
    )

    api_key: str | None = None
    api_key_header: str = "X-API-Key"

    bearer_token: str | None = None

    timeout_seconds: float = 30.0

    max_retries: int = 3

    retry_base_seconds: float = 0.5

    max_response_bytes: int = 10_000_000

    max_download_bytes: int = 500_000_000

    max_search_items: int = 100

    max_scene_age_hours: int = 72

    source_verified: bool = False

    require_verified_source: bool = True

    allowed_catalog_hosts: tuple[str, ...] = ()

    allowed_asset_hosts: tuple[str, ...] = ()

    allow_local_http_testing: bool = False

    def __post_init__(self) -> None:
        parsed = urlparse(
            self.stac_base_url
        )

        if not parsed.hostname:
            raise SatelliteConfigurationError(
                "Valid STAC base URL required"
            )

        if (
            parsed.username
            or parsed.password
            or parsed.query
            or parsed.fragment
        ):
            raise SatelliteConfigurationError(
                "Invalid STAC base URL components"
            )

        if parsed.scheme != "https":
            local_testing = (
                self.allow_local_http_testing
                and parsed.scheme == "http"
                and parsed.hostname in {
                    "localhost",
                    "127.0.0.1",
                    "::1",
                }
            )

            if not local_testing:
                raise SatelliteConfigurationError(
                    "HTTPS required"
                )

        if (
            self.allowed_catalog_hosts
            and parsed.hostname
            not in self.allowed_catalog_hosts
        ):
            raise SatelliteConfigurationError(
                "Catalog host not allowlisted"
            )

        if (
            not self.search_endpoint.startswith("/")
            or self.search_endpoint.startswith("//")
            or "://" in self.search_endpoint
            or "?" in self.search_endpoint
            or "#" in self.search_endpoint
            or ".." in self.search_endpoint.split("/")
        ):
            raise SatelliteConfigurationError(
                "Invalid search endpoint"
            )

        if (
            self.auth_type == SatelliteAuthType.API_KEY
            and not self.api_key
        ):
            raise SatelliteConfigurationError(
                "API key required"
            )

        if (
            self.auth_type == SatelliteAuthType.BEARER
            and not self.bearer_token
        ):
            raise SatelliteConfigurationError(
                "Bearer token required"
            )

        if self.timeout_seconds <= 0:
            raise SatelliteConfigurationError(
                "Timeout must be positive"
            )

        if self.max_retries < 0:
            raise SatelliteConfigurationError(
                "Invalid retry count"
            )

        for name in (
            "max_response_bytes",
            "max_download_bytes",
            "max_search_items",
            "max_scene_age_hours",
        ):
            if getattr(self, name) <= 0:
                raise SatelliteConfigurationError(
                    f"{name} must be positive"
                )


